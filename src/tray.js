// tray.js — the app's entire "settings UI": a native tray icon + context
// menu. Deliberately no renderer settings screen for v1.
const { Tray, Menu, app, nativeImage } = require("electron");
const path = require("path");
const { getEnv, setEnv, ENV_URLS, ENV_LABELS } = require("./config");
const { showMainWindow, openNotes, openRecordMeeting } = require("./windowManager");

let tray = null;
let updateReadyInfo = null; // { version } once electron-updater has a build ready
let checkForUpdatesNow = () => {};

function switchEnv(env) {
  if (getEnv() === env) return;
  setEnv(env);
  // Simplest correct way to reload the whole window against the new
  // origin — a fresh persistent session partition stays the same, only
  // the loaded URL's origin changes.
  app.relaunch();
  app.exit();
}

function buildMenuTemplate() {
  const env = getEnv();
  const template = [
    { label: "Show MyGenie Notes", click: () => showMainWindow() },
    { label: "Notes List", click: () => openNotes() },
    { label: "Open Record Meeting (old)", click: () => openRecordMeeting() },
    { type: "separator" },
    { label: "Check for Updates Now", click: () => checkForUpdatesNow() },
    {
      label: "Environment",
      // Built from config's ENV_URLS so a new dev slot only has to be added
      // there, not in two places that can drift apart.
      submenu: Object.keys(ENV_URLS).map((key) => ({
        label: ENV_LABELS[key] || key,
        type: "radio",
        checked: env === key,
        click: () => switchEnv(key),
      })),
    },
  ];

  if (updateReadyInfo) {
    template.push({ type: "separator" });
    template.push({
      label: `Restart to Install Update (v${updateReadyInfo.version})`,
      click: () => {
        app.isQuitting = true;
        // Actual install is triggered from updater.js's own handler, which
        // owns the autoUpdater instance — quitting here is enough to let
        // autoInstallOnAppQuit take over if the user didn't use the dialog.
        app.quit();
      },
    });
  }

  template.push({ type: "separator" });
  template.push({
    label: "Quit",
    click: () => {
      app.isQuitting = true;
      app.quit();
    },
  });

  return template;
}

function rebuildTray() {
  if (!tray) return;
  tray.setContextMenu(Menu.buildFromTemplate(buildMenuTemplate()));
}

// macOS menu bar: a monochrome *Template.png (macOS tints it for light/dark
// bars and picks up the @2x file automatically) — generated by
// scripts/make-tray-icon.js. Windows: the colour app icon, which lives under
// src/ so it is actually inside the packaged asar.
function trayIcon() {
  if (process.platform === "darwin") {
    const img = nativeImage.createFromPath(path.join(__dirname, "assets", "trayTemplate.png"));
    img.setTemplateImage(true);
    return img;
  }
  const img = nativeImage.createFromPath(path.join(__dirname, "widget", "icon.png"));
  return img.isEmpty() ? img : img.resize({ width: 16, height: 16 });
}

function createTray({ onCheckForUpdates } = {}) {
  if (onCheckForUpdates) checkForUpdatesNow = onCheckForUpdates;
  tray = new Tray(trayIcon());
  tray.setToolTip(`${app.getName()} v${app.getVersion()}`);
  // On macOS a click opens the menu (menu-bar convention); on Windows a
  // left click shows the window and right click opens the menu.
  if (process.platform !== "darwin") tray.on("click", () => showMainWindow());
  rebuildTray();
  return tray;
}

function setUpdateReady(version) {
  updateReadyInfo = { version };
  rebuildTray();
}

module.exports = { createTray, setUpdateReady, rebuildTray };
